package bench

import (
	"context"

	"github.com/AlexS8332/AnimalGuide/internal/features"
)

// MCPName — имя механизма MCP в реестре. Запись в features появляется
// вместе с клиентом; до тех пор испытание отмечается как не гонявшееся.
const MCPName features.Name = "mcp"

// MCP — место для И-7: тот же набор инструментов источников через
// MCP-сервер. Дорожки: A — умолчания + mcp, B — умолчания, B′ — повтор B
// (Lane.Same) для замера шума модели. Сценарий — запросы И-1, три раздела,
// узел дерева и сравнение; на дорожке A сервер убивается посреди прогона.
//
// Жёсткие проверки, которые реализация обязана заполнить:
//
//   - байты описаний инструментов в каждом запросе, A против B — совпадают
//     (отпечаток Fingerprint в событии «промпт»);
//   - постоянная часть запроса, A − B — 0 токенов;
//   - доля вызовов источников через MCP (Event.Via) — A 100 %, B 0 %;
//   - пороги И-1 — на обеих дорожках;
//   - ходов с Effective ≠ Requested — 0 (LaneStats.Brak);
//   - сервер убит посреди хода — ход завершён, модель получила ошибку,
//     следующий ход с перезапуском.
//
// Отчётные числа: отношение времени A/B, доля кэша, холодный старт,
// накладные на вызов, число HTTP-запросов к источникам, тексты ошибок,
// совпадение последовательностей вызовов A/B против B/B′.
type MCP struct {
	// Impl — реализация испытания; nil — испытание ещё не написано.
	Impl Trial
}

func (*MCP) ID() string    { return "И-7" }
func (*MCP) Title() string { return "MCP: тот же путь до источников" }

// Run — реализация, если она есть; иначе испытание пропускается с причиной.
func (m *MCP) Run(ctx context.Context, s *Stand, r *Result) error {
	r.Goal = "тот же набор инструментов через MCP-сервер: ответы, цена и журнал совпадают с локальным путём"
	if _, ok := s.env.Registry.Get(MCPName); !ok {
		r.Skipped = "механизма «mcp» нет в реестре: клиент MCP ещё не подключён"
		return nil
	}
	if m.Impl == nil {
		r.Skipped = "механизм «mcp» в реестре есть, но испытание не реализовано"
		return nil
	}
	return m.Impl.Run(ctx, s, r)
}
